def seed_failure_cases(db: Session) -> int:
    """插入失败案例种子数据。若已有数据则跳过。

    Returns:
        新增的案例数量
    """
    existing = db.query(FailureCase).count()
    if existing > 0:
        return 0

    for case_data in SEED_CASES:
        case = FailureCase(
            author_role=case_data["author_role"],
            path_type=case_data["path_type"],
            stage=case_data["stage"],
            title=case_data["title"],
            story=case_data["story"],
            lessons=case_data["lessons"],
            regrets=case_data["regrets"],
            what_would_i_do=case_data["what_would_i_do"],
            status="approved",  # 种子数据直接通过审核
        )
        db.add(case)

    db.commit()
    return len(SEED_CASES)
