"""招生情报内容判定（docs/爬取审核策略-2026-09-26 §3.1 口径的首个代码实现）。

背景：审核策略文档 09-26 就写明"招生情报=APPROVE、校内行政通知=REJECT"，但全仓
从未实现——三闸门只认来源历史统计（reputation）与质量分，不认条目内容，结果是
2026-10-01 实测 45 条 PENDING 全被信誉闸卡死（official_announce 通过率 0.8876
差 0.012 卡死 15 条真招生公告）。本模块把那条口径落成纯函数。

**适用范围（刻意收窄）**：调用方只对 ``credibility == "official_verified"`` 的条目
使用本规则。user_reported（社区/知乎路由）2026-10-01 实测 8 条噪声 0 条落进招生桶，
无需内容规则保护——不扩到噪声源，是防止 rsshub 那类 0.42 通过率的源被放松。

**判定规则**（命中即过）：
1. 标题+正文命中任一"招生锚点"词（ADMISSION_KEYWORDS）；
2. 且不命中任何"校内行政排除词"（ADMIN_NOISE_KEYWORDS）。

排除词表刻意保守：**不含"公示"**——"各学院接收推荐免试研究生结果公示"是典型招生情报，
把公示当噪声会误杀真情报（这是 2026-10-01 测算里踩到的坑）。排除词只收**语义上
不可能属于招生情报**的类别：竞赛评奖、党务值班、选课补采、住宿体检等。

不使用裸"报名"作锚点：西安交大/山大科技"竞赛报名中"会误命中（2026-10-01 实测误判
约 25% 的主因），故只认"报名点/网上报名"这类招生专用搭配。

纯函数、无副作用、无 IO；正负例由 tests/test_admission_content_rule.py 锁定。
"""

from __future__ import annotations

# 招生锚点：命中任一即视为可能属招生情报（需再过排除词）
ADMISSION_KEYWORDS: tuple[str, ...] = (
    "招生",
    "录取",
    "推免",
    "推荐免试",
    "复试",
    "调剂",
    "分数线",
    "章程",
    "专业目录",
    "考试大纲",
    "参考书目",
    "报考",
    "报考点",
    "网上报名",
    "报名点",
    "招生计划",
    "报考资格",
    "夏令营",
    "选调",
    "公派",
    "初试",
    "复试线",
    "资格线",
)

# 说明：刻意**不含**裸"硕士"/"博士"——那是学位词不是招生动作词。2026-10-01 生产
# dry-run 实测：保留"硕士"会让《申请学位成果要求备案通知》《研究生学籍信息核查
# 通知》两条校内行政通知被误放（只命中"硕士"一项），13 条放行里 2 条是误判。
# 真正的招生信息必然同时带"招生/报考/录取/目录/大纲/简章"等动作词或文件名。

# 校内行政排除词：命中即否决（"看似招生实为校内事务"的已知模式）
ADMIN_NOISE_KEYWORDS: tuple[str, ...] = (
    "竞赛",
    "大赛",
    "评选",
    "十佳",
    "班长",
    "党支部",
    "观影",
    "值班",
    "补课",
    "选课",
    "退选",
    "补选",
    "图采",
    "补采",
    "课程考试",
    "考试安排",
    "宿舍",
    "体检",
    "离校",
    "回国",
    "督导",
    "研修会议",
    "困难补助",
    "助学金",
    "励志",
    "奖学金",
    "来校",
    "来访",
    # 学位申请属录取后的行政事务，对考研决策无用（与"招生"相反），故按噪声处理
    "学位申请",
)


def classify_admission_item(title: str, content: str = "") -> tuple[bool, str]:
    """判定一条官方来源条目是否属招生情报。

    Returns:
        ``(True, reason)`` 命中招生锚点且不命中排除词——reason 列出命中的锚点词；
        ``(False, reason)`` 否则——reason 说明是"未命中任何招生锚点"还是
        "命中校内行政排除词 X"（后者是更重要的拒收理由，便于人工复核）。
    """
    # 只用标题 + 正文前段参与判定：external_meta.tags 是不可信 SEO 杂糅
    # （见 app/crawlers/research/transformer.py 09-02 生产假阳性教训）
    blob = f"{title or ''}\n{(content or '')[:2000]}"

    noise = [k for k in ADMIN_NOISE_KEYWORDS if k in blob]
    if noise:
        return False, f"命中校内行政排除词：{'/'.join(noise[:3])}"

    hits = [k for k in ADMISSION_KEYWORDS if k in blob]
    if hits:
        return True, f"命中招生锚点：{'/'.join(hits[:3])}"
    return False, "未命中任何招生锚点"
