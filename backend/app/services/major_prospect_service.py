def _category_of(major: str) -> str | None:
    """按关键词推断学科门类。"""
    for kw, cat in _CATEGORY_RULES:
        if kw in major:
            return cat
    return None


def _normalize_major(major: str) -> str:
    """归一化：去掉括号方向后缀（如"计算机（大数据方向）"→"计算机"）和空白。"""
    import re

    return re.sub(r"[（(].*?[)）]", "", major).strip()


def resolve_major(major: str) -> tuple[str, MajorEntry | None]:
    """解析专业名 → (规范名, 映射条目或 None)。先精确匹配，再互相包含匹配，最后门类兜底。"""
    major = _normalize_major(major)
    if major in MAJOR_MAP:
        return major, MAJOR_MAP[major]
    # 互相包含：处理"计算机"→"计算机科学与技术"、"会计（注册会计师方向）"→"会计"
    for name, entry in MAJOR_MAP.items():
        if name in major or major in name:
            return name, entry
    return major, None


def _fallback_entry(major: str) -> MajorEntry:
    cat = _category_of(major)
    if cat and cat in _CATEGORY_FALLBACK:
        return _CATEGORY_FALLBACK[cat]
    return _CATEGORY_FALLBACK["工学"]


def list_majors(db: Session) -> list[dict]:
    """所有可选专业：映射表主干 + grad_school_intel 实际收录专业。"""
    grad_majors = [
        row[0] for row in db.query(GradSchoolIntel.major_name).distinct().all() if row[0]
    ]
    mapped = []
    for name, entry in MAJOR_MAP.items():
        mapped.append(
            {
                "name": name,
                "category": entry.category,
                "source": "mapped",
                "has_grad_intel": name in grad_majors or any(g and name in g for g in grad_majors),
            }
        )
    mapped_names = {m["name"] for m in mapped}
    for g in grad_majors:
        if g in mapped_names:
            continue
        # grad 里的专业若被映射条目包含关系覆盖（如"道路与铁道工程"），跳过
        if any(g in m or m in g for m in mapped_names):
            continue
        _, entry = resolve_major(g)
        cat = entry.category if entry else (_category_of(g) or "工学")
        mapped.append({"name": g, "category": cat, "source": "grad_intel", "has_grad_intel": True})
    mapped.sort(key=lambda x: (x["category"], x["name"]))
    return mapped


def _industry_salaries(db: Session, industries: list[str]) -> list[dict]:
    """行业薪资：按行业取最新年份的非私营/私营年平均工资（国家统计局）。"""
    if not industries:
        return []
    rows = (
        db.query(MarketData)
        .filter(MarketData.category == "行业", MarketData.industry.in_(industries))
        .all()
    )
    latest_year = max((r.year for r in rows), default=None)
    if not latest_year:
        return []
    grouped: dict[str, dict] = {}
    for r in rows:
        if r.year != latest_year:
            continue
        g = grouped.setdefault(
            r.industry or "", {"non_private": None, "private": None, "prev_non_private": None}
        )
        # 城镇非私营单位薪资显著高于私营，用大小区分口径
        if r.indicator and "非私营" in r.indicator:
            if g["non_private"] is None or r.value > g["non_private"]:
                g["non_private"] = r.value
        elif r.indicator and "私营" in r.indicator:
            if g["private"] is None or r.value > g["private"]:
                g["private"] = r.value
    result = []
    for ind in industries:
        g = grouped.get(ind)
        if not g or g["non_private"] is None:
            continue
        result.append(
            {
                "industry": ind,
                "year": latest_year,
                "salary_non_private": g["non_private"],
                "salary_private": g["private"],
                "vs_national": round(g["non_private"] / _NATIONAL_AVG_2025, 2),
                "source": "国家统计局",
            }
        )
    result.sort(key=lambda x: x["salary_non_private"], reverse=True)
    return result


def _position_salaries(db: Session, keywords: list[str]) -> list[dict]:
    """岗位薪资：人社局市场工资价位按职位聚合。"""
    if not keywords:
        return []
    rows = db.query(SalaryBenchmark).all()
    agg: dict[str, dict] = {}
    for r in rows:
        if not any(kw in (r.position or "") for kw in keywords):
            continue
        a = agg.setdefault(
            r.position,
            {
                "medians": [],
                "mins": [],
                "maxs": [],
                "cities": set(),
                "source": r.source,
                "year": r.year,
            },
        )
        a["medians"].append(r.salary_median)
        a["mins"].append(r.salary_min)
        a["maxs"].append(r.salary_max)
        if r.city:
            a["cities"].add(r.city)
    result = []
    for pos, a in agg.items():
        result.append(
            {
                "position": pos,
                "salary_median": int(sum(a["medians"]) / len(a["medians"])),
                "salary_min": min(a["mins"]),
                "salary_max": max(a["maxs"]),
                "cities": sorted(a["cities"])[:6],
                "source": a["source"],
                "year": a["year"],
            }
        )
    result.sort(key=lambda x: x["salary_median"], reverse=True)
    return result[:12]


_SIZE_ORDER = {"giant": 0, "large": 1, "medium": 2, "small": 3, "startup": 4}


def _companies(db: Session, keywords: list[str], limit: int = 12) -> list[dict]:
    if not keywords:
        return []
    rows = db.query(Company).all()
    matched = [r for r in rows if any(kw in (r.industry or "") for kw in keywords)]
    matched.sort(key=lambda r: (_SIZE_ORDER.get(getattr(r.size, "value", str(r.size)), 9), r.name))
    return [
        {
            "name": r.name,
            "industry": r.industry,
            "size": getattr(r.size, "value", str(r.size)),
            "headquarters": r.headquarters,
        }
        for r in matched[:limit]
    ]


def _grad_paths(db: Session, aliases: list[str], major: str, limit: int = 12) -> list[dict]:
    """考研路径：grad_school_intel 按专业名匹配；score_line<=0 为占位脏数据须过滤（已知坑）。"""
    rows = db.query(GradSchoolIntel).all()
    name = major
    matched = []
    for r in rows:
        mn = r.major_name or ""
        hit = mn == name or name in mn or mn in name
        if not hit and aliases:
            hit = any(a and (a in mn or mn in a) for a in aliases)
        if hit:
            # score_line<=0 是占位脏数据（已知坑），直接过滤
            if not r.score_line or r.score_line <= 0:
                continue
            matched.append(r)
    # 分数线已过滤脏数据，直接按分数线降序
    matched.sort(key=lambda r: -(r.score_line or 0))

    def _ratio(v):
        return v if v else "—"

    return [
        {
            "school_name": r.school_name,
            "school_tier": r.school_tier,
            "major_name": r.major_name,
            "year": r.year,
            "admission_ratio": _ratio(r.admission_ratio),
            "score_line": r.score_line,
            "push_ratio": _ratio(r.push_ratio),
            "background_discrimination": r.background_discrimination,
            "first_choice_protection": r.first_choice_protection,
        }
        for r in matched[:limit]
    ]


