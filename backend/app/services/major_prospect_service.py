@dataclass
class MajorEntry:
    """专业映射条目。"""

    category: str  # 学科门类
    industries: list[str]  # 对口行业（market_data.industry 全名）
    position_keywords: list[str]  # 岗位关键词（salary_benchmarks.position 子串匹配）
    company_keywords: list[str]  # 公司行业关键词（companies.industry 子串匹配）
    grad_aliases: list[str]  # 考研专业别名（grad_school_intel.major_name 子串匹配）
    civil_service: str  # high / medium / low
    civil_note: str  # 考公说明
    related: list[str] = field(default_factory=list)  # 相近专业（前端跳转推荐）


def _e(
    category: str,
    industries: list[str],
    position_kw: list[str],
    company_kw: list[str],
    grad: list[str],
    civil: str,
    civil_note: str,
    related: list[str] | None = None,
) -> MajorEntry:
    return MajorEntry(
        category=category,
        industries=industries,
        position_keywords=position_kw,
        company_keywords=company_kw,
        grad_aliases=grad,
        civil_service=civil,
        civil_note=civil_note,
        related=related or [],
    )


