class TestTrajectory:
    def _post(self, client, auth_headers, payload):
        return client.post("/api/growth/trajectory", headers=auth_headers, json=payload)

    def test_create_ok(self, auth_headers, client):
        resp = self._post(
            client, auth_headers,
            {
                "event_type": "milestone",
                "event_payload": {"milestone": "拿到了第一份实习"},
                "occurred_at": datetime.now(timezone.utc).isoformat(),
                "source_event_id": "evt-001",
            },
        )
        assert resp.status_code == 200, resp.text
        body = resp.json()
        assert body["event_type"] == "milestone"
        assert body["user_id"]  # UUID 已注入
        assert body["source_event_id"] == "evt-001"

    def test_source_event_id_idempotent(self, auth_headers, client):
        """相同 source_event_id 重复提交 → 返回同一事件，不新增。"""
        payload = {
            "event_type": "milestone",
            "event_payload": {"x": 1},
            "occurred_at": datetime.now(timezone.utc).isoformat(),
            "source_event_id": "evt-dup",
        }
        first = self._post(client, auth_headers, payload).json()
        second = self._post(client, auth_headers, payload).json()
        assert first["id"] == second["id"]
        resp = client.get("/api/growth/trajectory", headers=auth_headers)
        assert resp.json()["total"] == 1

    def test_list_sorted_desc(self, auth_headers, client):
        base = datetime.now(timezone.utc)
        self._post(client, auth_headers, {
            "event_type": "milestone",
            "event_payload": {"n": 1},
            "occurred_at": (base - timedelta(minutes=2)).isoformat(),
            "source_event_id": "evt-a",
        })
        self._post(client, auth_headers, {
            "event_type": "review_completed",
            "event_payload": {"n": 2},
            "occurred_at": base.isoformat(),
            "source_event_id": "evt-b",
        })
        items = client.get("/api/growth/trajectory", headers=auth_headers).json()["items"]
        assert [i["event_type"] for i in items] == ["review_completed", "milestone"]


