class TestArchive:
    def test_empty_archive_autogenerated(self, auth_headers, client):
        """无行动时档案自动聚合生成全零快照。"""
        resp = client.get("/api/growth/archive", headers=auth_headers)
        assert resp.status_code == 200
        body = resp.json()
        assert body["total_actions"] == 0
        assert body["completed_actions"] == 0
        assert body["action_completion_rate"] == 0.0
        assert body["weighted_action_score"] == 0.0
        assert body["archive_status"] == "ACTIVE"
        assert body["updated_at"]  # 契约 updated_at 已映射

    def test_archive_aggregates_actions(self, auth_headers, client):
        """2 个行动（权重 1+15），完成权重 15 → 完成率 0.5、加权分 93.75。"""
        a1 = _create_action(client, auth_headers, action_type="read_article")  # weight 1
        a2 = _create_action(client, auth_headers, action_type="mock_interview")  # weight 15
        _checkin(client, auth_headers, a2["id"])

        resp = client.get("/api/growth/archive", headers=auth_headers)
        body = resp.json()
        assert body["total_actions"] == 2
        assert body["completed_actions"] == 1
        assert body["action_completion_rate"] == 0.5
        assert body["weighted_action_score"] == 93.75
        assert body["streak_days"] == 1
        assert a1["id"] != a2["id"]

    def test_refresh_endpoint(self, auth_headers, client):
        a = _create_action(client, auth_headers)
        resp = client.put("/api/growth/archive/refresh", headers=auth_headers)
        assert resp.status_code == 200
        body = resp.json()
        assert body["total_actions"] == 1
        assert body["completed_actions"] == 0
        # 打卡后再刷新
        _checkin(client, auth_headers, a["id"])
        resp = client.put("/api/growth/archive/refresh", headers=auth_headers)
        body = resp.json()
        assert body["completed_actions"] == 1

    def test_refresh_does_not_require_path_user_id(self, auth_headers, client):
        """旧契约 /archive/{user_id}/refresh 已改为当前用户，无越权路径参数。"""
        resp = client.put("/api/growth/archive/refresh", headers=auth_headers)
        assert resp.status_code == 200


